"""
Trace art/muscle-map.png into src/icons/bodyPaths.ts.

The source image is a flat colour-coded muscle map, front view on the left and
back view on the right, with one solid colour per muscle group. Each pixel is
snapped to the nearest palette colour, each group is traced into outline paths,
and both views are fitted to the left 15 units of the 24x24 icon grid.

    pip install numpy pillow opencv-python-headless
    python3 scripts/trace-muscle-map.py
"""
import json
import os

import cv2
import numpy as np
from PIL import Image

PALETTE = {
    'bg': (255, 255, 255),
    'chest': (0xE5, 0x39, 0x35),
    'shoulders': (0xFB, 0x8C, 0x00),
    'arms': (0xFD, 0xD8, 0x35),
    'core': (0x43, 0xA0, 0x47),
    'back': (0x1E, 0x88, 0xE5),
    'legs': (0x8E, 0x24, 0xAA),
    'neutral': (0xBD, 0xBD, 0xBD),
}
REGIONS = ['neutral', 'chest', 'shoulders', 'arms', 'core', 'back', 'legs']

# Figure height and placement on the 24x24 grid.
HEIGHT, TOP, CENTRE_X = 23.4, 0.3, 7.5


def label_pixels(path):
    """Index into PALETTE of the nearest colour, per pixel."""
    img = np.asarray(Image.open(path).convert('RGB'), float)
    colours = np.array(list(PALETTE.values()), float)
    return ((img[:, :, None, :] - colours[None, None]) ** 2).sum(-1).argmin(-1)


def trace(path):
    lab = label_pixels(path)
    idx = {name: i for i, name in enumerate(PALETTE)}
    width = lab.shape[1]
    fg = lab != idx['bg']

    boxes = {}
    for view, (x0, x1) in {'front': (0, width // 2), 'back': (width // 2, width)}.items():
        ys, xs = np.nonzero(fg[:, x0:x1])
        boxes[view] = (xs.min() + x0, xs.max() + x0, ys.min(), ys.max())
    # One scale for both views, so they are the same body.
    scale = HEIGHT / max(b[3] - b[2] for b in boxes.values())

    views = {}
    for view, (xa, xb, ya, _) in boxes.items():
        cx = (xa + xb) / 2
        masks = {}
        for region in REGIONS:
            m = (lab == idx[region]).astype(np.uint8)
            m[:, : xa - 2] = 0
            m[:, xb + 3 :] = 0
            masks[region] = m

        if view == 'front':
            # The generator coloured the front traps as shoulders. They are
            # back, and the pieces nearest the midline are the traps.
            n, comp, _, centroids = cv2.connectedComponentsWithStats(masks['shoulders'])
            for k in range(1, n):
                if abs(centroids[k][0] - cx) < 0.2 * (xb - xa):
                    masks['back'][comp == k] = 1
                    masks['shoulders'][comp == k] = 0

        out = {}
        for region in REGIONS:
            # Opening drops the anti-aliased fringe that snaps to grey.
            m = cv2.morphologyEx(masks[region], cv2.MORPH_OPEN, np.ones((3, 3), np.uint8), iterations=2)
            contours, _ = cv2.findContours(m, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
            parts = []
            for c in contours:
                if cv2.contourArea(c) < 60:
                    continue
                c = cv2.approxPolyDP(c, 1.6, True)
                pts = [(CENTRE_X + (x - cx) * scale, TOP + (y - ya) * scale) for [[x, y]] in c]
                parts.append('M' + ' '.join(f'{x:.2f} {y:.2f}' for x, y in pts) + 'Z')
            if parts:
                out[region] = ''.join(parts)
        views[view] = out
    return views


if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    views = trace(os.path.join(root, 'art', 'muscle-map.png'))
    lines = [
        '// Generated by scripts/trace-muscle-map.py from art/muscle-map.png. Do not edit.',
        "import type { MuscleGroup } from '../types'",
        '',
        "export type Region = MuscleGroup | 'neutral'",
        '',
        "export const BODY_PATHS: Record<'front' | 'back', Partial<Record<Region, string>>> = {",
    ]
    for view, regions in views.items():
        lines.append(f'  {view}: {{')
        for region, d in regions.items():
            lines.append(f'    {region}: {json.dumps(d)},')
        lines.append('  },')
    lines.append('}')
    with open(os.path.join(root, 'src', 'icons', 'bodyPaths.ts'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
